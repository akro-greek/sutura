module Exports
  class Epidoc
    def initialize(scroll)
      @scroll = scroll
    end

    def call
      builder = Nokogiri::XML::Builder.new(encoding: "UTF-8") do |xml|
        xml.TEI("xmlns" => "http://www.tei-c.org/ns/1.0") do
          xml.teiHeader do
            xml.fileDesc do
              xml.titleStmt { xml.title @scroll.title }
              xml.publicationStmt { xml.p "Generated by Sutura Scrolls" }
              xml.sourceDesc { xml.p @scroll.source_artifacts.map(&:citation).join("; ") }
            end
          end
          xml.text_ do
            xml.body do
              xml.div(type: "edition", "xml:lang" => @scroll.language) do
                @scroll.passages.ordered_columns.each do |column|
                  xml.div(type: "textpart", subtype: "column", n: column.label) do
                    column.children.lines.each { |line| xml.l(line.reading&.diplomatic_text.to_s, n: line.label) }
                  end
                end
              end
            end
          end
        end
      end
      builder.to_xml
    end
  end
end
